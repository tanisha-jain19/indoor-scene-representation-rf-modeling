"""Run the prepared stages with durable logs; resume after a Colab interruption.

Invoke with /content/wrfgs_env/bin/python after setup, with WRF_RUN_DIR pointing
to the mounted Drive folder. No training or success results are fabricated.
"""
import argparse
import datetime
import json
import os
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parent

def utc_now():
    return datetime.datetime.now(datetime.timezone.utc).isoformat()

def write_status(path, payload):
    temp = path.with_suffix('.tmp')
    temp.write_text(json.dumps(payload, indent=2), encoding='utf-8')
    temp.replace(path)

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--iterations', type=int, default=10000)
    parser.add_argument('--through', choices=['pilot', 'data', 'train', 'evaluate'], default='pilot')
    args = parser.parse_args()
    out = Path(os.environ.get('WRF_RUN_DIR', str(ROOT/'run_fullroom')))
    out.mkdir(parents=True, exist_ok=True)
    logs = out/'execution_logs'
    logs.mkdir(exist_ok=True)
    status_path = out/'execution_status.json'
    session = datetime.datetime.now(datetime.timezone.utc).strftime('%Y%m%dT%H%M%SZ')

    def stage(name, command):
        log_path = logs/f'{session}_{name}.log'
        record = {'stage': name, 'state': 'running', 'started_utc': utc_now(),
                  'command': command, 'log': str(log_path)}
        write_status(status_path, record)
        print(f'\nSTAGE: {name}\nLog: {log_path}', flush=True)
        with log_path.open('w', encoding='utf-8', buffering=1) as log:
            process = subprocess.Popen(command, cwd=ROOT, stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT, text=True, encoding='utf-8', errors='replace',
                bufsize=1, env={**os.environ, 'PYTHONUNBUFFERED': '1'})
            try:
                for line in process.stdout:
                    print(line, end='', flush=True)
                    log.write(line)
                result = process.wait()
            except BaseException:
                process.terminate()
                process.wait()
                record.update(state='interrupted', finished_utc=utc_now())
                write_status(status_path, record)
                raise
        record.update(state='passed' if result == 0 else 'failed',
                      return_code=result, finished_utc=utc_now())
        write_status(status_path, record)
        if result:
            raise RuntimeError(f'{name} failed. Full output saved in {log_path}; later stages were not run.')

    py = sys.executable
    stage('cpu_checks', [py, '-m', 'unittest', 'test_rf_math.py', '-v'])
    stage('gpu_checks', [py, 'verify_runtime.py'])
    stage('room_preparation', [py, 'generate_data.py', 'prepare'])
    stage('pilot', [py, 'generate_data.py', 'pilot'])
    if args.through == 'pilot':
        print('Pilot stages finished. Inspect room_plan.png and pilot_rf_images.png before continuing.')
        return
    stage('data_generation', [py, 'generate_data.py', 'all'])
    if args.through == 'data': return
    checkpoint = out/'model'/'last.pt'
    step = 0
    if checkpoint.exists():
        import torch
        # Only load a checkpoint generated by this experiment in the user's folder.
        step = int(torch.load(checkpoint, map_location='cpu', weights_only=False)['iteration'])
    if step < args.iterations:
        command = [py, 'train_room.py', 'train', '--iterations', str(args.iterations)]
        if checkpoint.exists(): command.append('--resume')
        stage('training', command)
    else:
        print(f'Existing checkpoint has {step} iterations; training skipped.', flush=True)
    if args.through == 'train': return
    stage('final_evaluation', [py, 'train_room.py', 'evaluate'])
    print('Final evaluation completed. Read evaluation/mentor_report.md for actual metrics and limitations.')

if __name__ == '__main__':
    main()
